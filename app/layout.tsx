// JSON-LD structured data for SEO
function JsonLd() {
  const structuredData = {
    '@context': 'https://schema.org',
    '@type': 'TravelAgency',
    name: 'MAPL Tours Jamaica',
    url: siteUrl,
    // Google wants a crawlable raster logo (>=112px); the SVG favicon route
    // is not reliable for this.
    logo: `${siteUrl}/brand/mapl-icon-1024.png`,
    description: 'Private airport transfers from Sangster (MBJ) at one flat price per vehicle, and private tours and day packages with hotel pickup, run with Jamaican drivers and hosts.',
    address: {
      '@type': 'PostalAddress',
      addressCountry: 'JM',
      addressRegion: 'Jamaica',
    },
    geo: {
      '@type': 'GeoCoordinates',
      // Montego Bay / Sangster (MBJ), where every transfer begins. Was the
      // Jamaica country centroid, which contradicted the geo meta tags below.
      latitude: 18.5037,
      longitude: -77.9134,
    },
    // Every locality the business actually serves. The transfers schema listed
    // three (Rose Hall, Lucea, Runaway Bay) that this one omitted, so the two
    // entities disagreed about the service area.
    areaServed: [
      { '@type': 'Country', name: 'Jamaica' },
      { '@type': 'City', name: 'Montego Bay' },
      { '@type': 'City', name: 'Rose Hall' },
      { '@type': 'City', name: 'Falmouth' },
      { '@type': 'City', name: 'Runaway Bay' },
      { '@type': 'City', name: 'Ocho Rios' },
      { '@type': 'City', name: 'Lucea' },
      { '@type': 'City', name: 'Negril' },
    ],
    priceRange: `$${cheapestRide} - $${dearestTour}`,
    // Note: aggregateRating intentionally omitted from the site-wide entity.
    // Google rejects "self-serving" reviews, ratings/reviews belong on the
    // specific thing reviewed (Product / Service / TouristTrip), not on the
    // business itself. Per-experience ratings live on /experience/[slug].
    hasOfferCatalog: {
      '@type': 'OfferCatalog',
      name: 'Jamaica Tours & Experiences',
      itemListElement: [
        {
          '@type': 'Offer',
          itemOffered: {
            '@type': 'TouristTrip',
            name: "Rick's Cafe Cliff Diving & Sunset",
            description: 'Jump from legendary cliffs as the sun melts into the Caribbean.',
            touristType: 'Adventure',
            offers: catalogOffer(tourById(14)),
          },
        },
        {
          '@type': 'Offer',
          itemOffered: {
            '@type': 'TouristTrip',
            name: 'Bob Marley Nine Mile Pilgrimage',
            description: 'Walk where Bob walked. Feel the spirit of One Love.',
            touristType: 'Culture',
            offers: catalogOffer(tourById(15)),
          },
        },
        {
          '@type': 'Offer',
          itemOffered: {
            '@type': 'TouristTrip',
            name: "Dunn's River Falls Climb",
            description: 'Climb 600 feet of cascading falls hand-in-hand.',
            touristType: 'Adventure',
            offers: catalogOffer(tourById(1)),
          },
        },
      ],
    },
    sameAs: [
      'https://www.instagram.com/mapltoursjamaica',
      'https://www.tiktok.com/@mapltoursjamaica',
    ],
  }

  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{ __html: JSON.stringify(structuredData) }}
    />
  )
}

